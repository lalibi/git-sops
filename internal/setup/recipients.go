var indexLine = regexp.MustCompile(`^(\d+)\s+[0-9a-f]+\s+0\t`)

func AddRecipient(o Options) error {
	if len(o.Recipients) == 0 && ui.Interactive() {
		answer, err := ui.Input(
			"Which age public recipient should get access?",
			"Paste the age1... value the collaborator sent you. Never paste an AGE-SECRET-KEY.",
			"age1...",
			"",
			func(s string) error {
				if !config.IsRecipient(strings.TrimSpace(s)) {
					return errors.New("not an age public recipient (expected age1...)")
				}
				return nil
			})
		if err != nil {
			return err
		}
		o.Recipients = []string{strings.TrimSpace(answer)}
		if o.RecipientName == "" {
			o.RecipientName, err = ui.Input("Collaborator name (optional)", "Shown by git-sops access. Press Enter to skip.", "Name or label", "", nil)
			if err != nil {
				return err
			}
		}
	}

	if len(o.Recipients) == 0 {
		return errors.New("add-recipient requires at least one age public recipient (age1...)")
	}
	if err := validateRecipients(o.Recipients); err != nil {
		return err
	}
	if o.RecipientName != "" {
		if len(o.Recipients) != 1 {
			return errors.New("--name applies to one recipient at a time")
		}
		if err := config.ValidateRecipientName(o.RecipientName); err != nil {
			return err
		}
		o.RecipientName = strings.TrimSpace(o.RecipientName)
	}

	_, err := changeRecipients(o, "add-recipient", func(current []string) ([]string, error) {
		return append(append([]string{}, current...), o.Recipients...), nil
	})
	if err != nil || o.DryRun {
		return err
	}

	ui.Box("Recipients updated",
		reviewChanges(o),
		"The new recipient can pull and run "+ui.Code("git-sops join")+".")
	return nil
}

// RemoveRecipient revokes recipients in the managed .sops.yaml and re-encrypts protected files without them.
func RemoveRecipient(o Options) error {
	if err := validateRecipients(o.Recipients); err != nil {
		return err
	}
	_, err := changeRecipients(o, "remove-recipient", func(current []string) ([]string, error) {
		toRemove := o.Recipients
		if len(toRemove) == 0 {
			if !ui.Interactive() {
				return nil, errors.New("remove-recipient requires at least one age public recipient (age1...)")
			}
			answer, err := ui.Input(
				"Which age public recipient should lose access?",
				"Current recipients:\n  "+strings.Join(current, "\n  "),
				"age1...",
				"",
				func(s string) error {
					if !slices.Contains(current, strings.TrimSpace(s)) {
						return errors.New("not a current recipient")
					}
					return nil
				})
			if err != nil {
				return nil, err
			}
			toRemove = []string{strings.TrimSpace(answer)}
		}

		for _, r := range toRemove {
			if !slices.Contains(current, r) {
				return nil, fmt.Errorf("'%s' is not a recipient in .sops.yaml", r)
			}
		}

		// Re-encrypting runs the clean filter against the new ciphertext, which needs this identity's key.
		if id, err := agekey.Load(); err == nil && id != nil && slices.Contains(toRemove, id.Recipient) {
			return nil, errors.New("refusing to remove the recipient of your own age identity; run this from another authorized identity")
		}

		var kept []string
		for _, r := range current {
			if !slices.Contains(toRemove, r) {
				kept = append(kept, r)
			}
		}
		if len(kept) == 0 {
			return nil, errors.New("refusing to remove the last recipient")
		}
		return kept, nil
	})
	if err != nil || o.DryRun {
		return err
	}

	ui.Box("Recipients updated",
		reviewChanges(o),
		"Old commits still hold ciphertext the removed recipient can decrypt.",
		"Rotate the real credentials they may have seen.")
	return nil
}

// changeRecipients rewrites the recipient list in the managed .sops.yaml, re-encrypts every
// protected file for it and validates the index. It returns the resulting recipient list.
func changeRecipients(o Options, command string, next func(current []string) ([]string, error)) ([]string, error) {
	e, err := NewEnv(o)
	if err != nil {
		return nil, err
	}
	ui.Header(command, e.Root)

	if err := assertCleanTrackedTree(e); err != nil {
		return nil, err
	}

	managed, err := config.ReadManaged(filepath.Join(e.Root, ".sops.yaml"))
	if err != nil {
		return nil, err
	}
	if managed == nil {
		return nil, fmt.Errorf("%s requires a .sops.yaml generated by git-sops", command)
	}
	if managed.Groups != nil || o.Group != "" || o.Everywhere || o.DryRun {
		return nil, editAccess(e, o, command)
	}

	specs, err := config.BuildSpecs(e.Root, managed.ProtectedPaths)
	if err != nil {
		return nil, err
	}

	all, err := next(managed.Recipients)
	if err != nil {
		return nil, err
	}
	all = config.UniqueRecipients(all)
	current := config.UniqueRecipients(managed.Recipients)
	membershipChanged := !slices.Equal(current, all)
	nameChanged := o.RecipientName != "" && managed.RecipientNames[o.Recipients[0]] != o.RecipientName
	if !membershipChanged && !nameChanged {
		ui.Okf("Recipients are unchanged; nothing to commit.")
		return all, nil
	}
	changed := recipientDifference(all, current)
	if command == "remove-recipient" {
		changed = recipientDifference(current, all)
	}

	managed.Recipients = all
	if nameChanged {
		managed.SetRecipientName(o.Recipients[0], o.RecipientName)
	}
	var files []string
	if membershipChanged {
		files, err = e.Git.TrackedFilterPaths(func(driver string) bool { return driver == "sops" })
		if err != nil {
			return nil, err
		}
	} else {
		changed = o.Recipients
	}

	err = pathTransaction(e, func() error {
		if err := config.WriteManagedConfig(e.Root, specs, managed, false, ui.Warnf); err != nil {
			return err
		}
		if err := ConfigureLocal(e); err != nil {
			return err
		}
		bar := ui.NewProgress("Re-encrypting", int64(len(files)), false)
		for i, path := range files {
			bar.Set(int64(i), path)
			if err := rekey(e, path); err != nil {
				bar.Abort()
				return err
			}
		}
		bar.Finish("Re-encrypted %d file(s) for %d recipient(s)", len(files), len(all))
		if !o.NoStage {
			if _, err := e.Git.Run(nil, "add", "--", ".sops.yaml"); err != nil {
				return fmt.Errorf("could not stage .sops.yaml: %w", err)
			}
		}
		return ValidateIndex(e)
	})
	if err != nil {
		return nil, err
	}
	if !membershipChanged {
		specs = nil
	}
	if err := commitChanges(e, o, command, specs, changed); err != nil {
		return nil, err
	}

	return all, nil
}

func stageCipher(e *Env, path string, encrypted []byte) error {
	hashOut, err := e.Git.Run(encrypted, "hash-object", "-w", "--no-filters", "--stdin")
	if err != nil {
		return err
	}
	hash := strings.TrimSpace(string(hashOut))

	stage, err := e.Git.Output("--literal-pathspecs", "ls-files", "--stage", "--", path)
	if err != nil {
		return err
	}
	m := indexLine.FindStringSubmatch(strings.SplitN(stage, "\n", 2)[0])
	if m == nil {
		return fmt.Errorf("could not determine the index mode for '%s'", path)
	}

	if _, err := e.Git.Run(nil, "update-index", "--cacheinfo", m[1]+","+hash+","+path); err != nil {
		return err
	}

	return nil
}

// rekey always starts from staged ciphertext. Working copies may already be
// decrypted, still be ciphertext, or have different structured formatting.
func rekey(e *Env, path string) error {
	abs := filepath.Join(e.Root, filepath.FromSlash(path))
	st, err := os.Lstat(abs)
	if err != nil {
		return err
	}
	if !st.Mode().IsRegular() {
		return fmt.Errorf("cannot re-encrypt non-regular file %q", path)
	}
	blob, err := e.Git.Run(nil, "cat-file", "blob", ":"+path)
	if err != nil {
		return err
	}
	plain, err := e.Sops.Decrypt(path, blob)
	if err != nil {
		return fmt.Errorf("current key must decrypt %q to change its recipients: %w", path, err)
	}
	cipher, err := e.Sops.Encrypt(path, plain)
	if err != nil {
		return fmt.Errorf("encrypt %q: %w", path, err)
	}
	if err := stageCipher(e, path, cipher); err != nil {
		return err
	}
	if _, err := e.Sops.Decrypt(path, cipher); err != nil {
		locked, policyErr := filter.Locked(e.Sops, path, cipher)
		if policyErr != nil {
			return policyErr
		}
		if !locked {
			return fmt.Errorf("verify new ciphertext for %q: %w", path, err)
		}
		// A maintainer can hand a file off to a group that excludes their own key.
		if err := e.writeWorkFile(path, cipher, st.Mode().Perm()); err != nil {
			return err
		}
	} else {
		work, err := worktree.ReadFile(e.Root, path)
		if err != nil {
			return err
		}
		if bytes.Equal(work, blob) {
			return e.writeWorkFile(path, plain, st.Mode().Perm())
		}
	}
	return nil
}
